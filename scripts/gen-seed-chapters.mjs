// Generates scripts/seed-chapters.sql from content/chapters-9.json.
//
//   node scripts/gen-seed-chapters.mjs
//
// The emitted SQL is idempotent: it ensures the five offered subjects exist,
// removes the subjects Prepify no longer teaches, and inserts any chapter that
// isn't already present (matched on book + seq). Run it in the Supabase SQL
// editor, or through the Supabase MCP connector.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const doc = JSON.parse(readFileSync(join(root, "content/chapters-9.json"), "utf8"));

const OFFERED = ["Physics", "Chemistry", "Maths", "Computer Science", "English"];
const DROPPED = ["Biology", "Islamiyat", "Pak Studies", "Urdu"];

const json = JSON.stringify({ class_level: doc._meta.class_level, subjects: doc.subjects });
if (json.includes("$hf$")) throw new Error("dollar-quote delimiter collision");

const sql = `-- Auto-generated by scripts/gen-seed-chapters.mjs from content/chapters-9.json.
-- Idempotent: safe to re-run. Ensures the five offered subjects, drops the rest,
-- and adds any missing chapter rows (matched on book + seq).
do $$
declare
  v_json    jsonb := $hf$${json}$hf$::jsonb;
  v_class   int   := (v_json->>'class_level')::int;
  v_subject uuid;
  v_book    uuid;
  v_name    text;
  sub jsonb;
  ch  jsonb;
  i   int;
begin
  -- 1. Ensure every offered subject exists.
  foreach v_name in array ${pgArray(OFFERED)}
  loop
    if not exists (select 1 from subjects where name = v_name) then
      insert into subjects(name) values (v_name);
    end if;
  end loop;

  -- 2. Remove subjects Prepify no longer teaches (clear enrolments first, since
  --    enrollments.subject_id has no cascade).
  delete from enrollments
   where subject_id in (select id from subjects where name = any(${pgArray(DROPPED)}));
  delete from subjects where name = any(${pgArray(DROPPED)});

  -- 3. Chapters per subject.
  for sub in select jsonb_array_elements(v_json->'subjects') loop
    select id into v_subject from subjects where name = sub->>'subject';
    if v_subject is null then
      raise exception 'Subject % missing', sub->>'subject';
    end if;

    select id into v_book from books
      where subject_id = v_subject and class_level = v_class
      order by id limit 1;
    if v_book is null then
      insert into books(subject_id, class_level, edition)
        values (v_subject, v_class, 'FBISE') returning id into v_book;
    end if;

    i := 0;
    for ch in select jsonb_array_elements(sub->'chapters') loop
      i := i + 1;
      if not exists (select 1 from chapters where book_id = v_book and seq = i) then
        insert into chapters(book_id, seq, title) values (v_book, i, ch #>> '{}');
      end if;
    end loop;
  end loop;
end $$;
`;

writeFileSync(join(root, "scripts/seed-chapters.sql"), sql);

const counts = doc.subjects.map((s) => `${s.subject}: ${s.chapters.length}`).join(", ");
console.log(`wrote scripts/seed-chapters.sql (${sql.length} bytes)`);
console.log(`chapters — ${counts}`);

function pgArray(items) {
  return `array[${items.map((s) => `'${s.replace(/'/g, "''")}'`).join(", ")}]`;
}
